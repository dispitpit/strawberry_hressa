#====================================================
# 正權重（+）：該波段的值越高，越傾向於分類到一個特定類別（例如 Unhealthy）。
# 負權重（−）：該波段的值越高，越傾向於分類到另一個類別（例如 Healthy）。
#====================================================

import numpy as np
import pandas as pd
from pathlib import Path
from sklearn.discriminant_analysis import LinearDiscriminantAnalysis as LDA
import matplotlib.pyplot as plt

plt.rcParams["font.family"] = "Times New Roman"
plt.rcParams["font.size"] = 16

# === 讀取資料 ===
healthy_dir = Path(r"D:/Users/Amanda/PycharmProjects/test/test_0415_LDA/重製1003/ks_npy_train_subset/healthy")
unhealthy_dir = Path(r"D:/Users/Amanda/PycharmProjects/test/test_0415_LDA/重製1003/ks_npy_train_subset/unhealthy")

X = []
y = []
file_names = []

# 載入樣本
for f in healthy_dir.glob("*.npy"):
    X.append(np.load(f))
    y.append("Healthy")
    file_names.append(f.name)

for f in unhealthy_dir.glob("*.npy"):
    X.append(np.load(f))
    y.append("Unhealthy")
    file_names.append(f.name)

X = np.array(X)
y = np.array(y)

wavelengths = np.load("wavelengths.npy").astype(float)   # shape = (n_bands,)
mask = (wavelengths >= 450.0) & (wavelengths <= 950.0)
assert X.shape[1] == wavelengths.shape[0], "波長數量需等於光譜欄數"
assert mask.dtype == bool and mask.shape[0] == X.shape[1]

X_sel = X[:, mask]
wavelengths_sel = wavelengths[mask]
print("原始:", X.shape, "→ 篩後:", X_sel.shape, "保留波段數:", mask.sum())

# === LDA（用篩後的 X_sel）===
lda = LDA(n_components=1)
X_lda = lda.fit_transform(X_sel, y)

# === 繪圖 ===
plt.figure(figsize=(8, 6))
for label, color in zip(["Healthy", "Unhealthy"], ["blue", "red"]):
    plt.scatter(X_lda[y == label], np.zeros_like(X_lda[y == label]),
                label=label, alpha=0.7, color=color)

plt.title("LDA Projection (1D)")
plt.xlabel("LDA Component 1")
plt.legend()
plt.grid(True)
plt.tight_layout()

# === 儲存 ===
save_path = f"LDA_Projection.png"
plt.savefig(save_path, dpi=300)
print(f"圖片已儲存至 {save_path}")
plt.show()

# === 投影保存 ===
lda_df = pd.DataFrame({
    "File": file_names,
    "Label": y,
    "LDA1": X_lda.flatten()
})
lda_df.to_csv("lda_projection_results.csv", index=False)
# print("LDA 投影結果已儲存為 lda_projection_results.csv")

# === LDA ===
lda_weights = lda.coef_[0]
top_k = 60
top_idx_sel = np.argsort(np.abs(lda_weights))[::-1][:top_k]

print(f"\n=== 前 {top_k} 個重要波段（LDA 權重排序，450–950 nm）===")
for idx in top_idx_sel:
    print(f"篩後索引: {idx:3d}, 原始索引: {np.flatnonzero(mask)[idx]:3d}, "
          f"波長: {wavelengths_sel[idx]:.2f} nm, 權重: {lda_weights[idx]:+.4f}")

# === 儲存重要波段資訊 ===
orig_cols = np.flatnonzero(mask)            # 篩後→原始欄位對照
top_bands_info = pd.DataFrame({
    "Band Index (after mask)": top_idx_sel,
    "Band Index (original)": orig_cols[top_idx_sel],
    "Wavelength (nm)": wavelengths_sel[top_idx_sel],
    "LDA Weight": lda_weights[top_idx_sel]
})
top_bands_info.to_csv("lda_top_bands.csv", index=False)
# print(f"已儲存重要波段至 lda_top_bands.csv")

print("finish")